// Bonus: generates website/config.js (addresses + ABIs) and copies the ethers.js
// browser bundle into website/vendor/, so the website works without any CDN.
//   NETWORK=sepolia | localhost
const fs = require("fs");
const path = require("path");
require("dotenv").config({ quiet: true });

const CODE_DIR = path.join(__dirname, "..");
const REPO_ROOT = path.join(CODE_DIR, "..");
const WEBSITE_DIR = path.join(REPO_ROOT, "website");

// Public endpoints only: never write SEPOLIA_RPC here, it may contain a private API key
const NETWORKS = {
  sepolia: { chainId: 11155111, chainName: "Sepolia", rpcUrl: "https://ethereum-sepolia-rpc.publicnode.com", explorer: "https://sepolia.etherscan.io" },
  localhost: { chainId: 31337, chainName: "Hardhat Localhost", rpcUrl: "http://127.0.0.1:8545", explorer: "" },
};

function loadAbi(contractName) {
  const artifact = path.join(CODE_DIR, "artifacts", "contracts", `${contractName}.sol`, `${contractName}.json`);
  if (!fs.existsSync(artifact)) throw new Error(`Missing ${artifact}. Run make compile first.`);
  return JSON.parse(fs.readFileSync(artifact, "utf8")).abi;
}

function main() {
  const networkName = process.env.NETWORK || "sepolia";
  const network = NETWORKS[networkName];
  if (!network) throw new Error(`Unknown NETWORK: ${networkName}`);

  const deploymentFile = path.join(REPO_ROOT, "deployment", `${networkName}.json`);
  const deployment = fs.existsSync(deploymentFile) ? JSON.parse(fs.readFileSync(deploymentFile, "utf8")) : {};

  const contracts = {};
  for (const [key, contractName] of [["nft", "Mokko42NFT"], ["inscriptions", "Mokko42Inscriptions"]]) {
    contracts[key] = {
      contractName,
      address: deployment[key] ? deployment[key].address : null,
      abi: loadAbi(contractName),
    };
    console.log(`${contractName}:`, contracts[key].address || "(not deployed)");
  }

  const config = {
    network: networkName,
    ...network,
    rpcUrl: process.env.WEBSITE_RPC || network.rpcUrl,
    ipfsGateway: process.env.IPFS_GATEWAY || "https://gateway.pinata.cloud/ipfs/",
    contracts,
  };

  fs.writeFileSync(
    path.join(WEBSITE_DIR, "config.js"),
    "// Generated by code/scripts/website_config.cjs - do not edit\n" +
      `window.TOKENIZEART_CONFIG = ${JSON.stringify(config, null, 2)};\n`
  );

  fs.mkdirSync(path.join(WEBSITE_DIR, "vendor"), { recursive: true });
  fs.copyFileSync(
    path.join(CODE_DIR, "node_modules", "ethers", "dist", "ethers.umd.min.js"),
    path.join(WEBSITE_DIR, "vendor", "ethers.umd.min.js")
  );

  console.log("Written: website/config.js, website/vendor/ethers.umd.min.js");
}

main();
